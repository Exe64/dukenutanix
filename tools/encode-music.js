#!/usr/bin/env node
// Turns the Suno exports dropped in music/src/ into the game's soundtrack: music/<theme>-<n>.mp3,
// stereo 96 kbps, -16 LUFS, cut to MAX seconds with a fade-out when longer, and js/music.js,
// the number of versions of each theme (the game plays them in turn, see Sfx.music).
// An export is named [dn-]<theme>[<number>|-a|-b].<ext>, e.g. dn-ep001.mp3, dn-ovh03.mp3,
// title.mp3; the theme is one the game plays (THEMES below). The raw exports stay out of git.
// Usage: node tools/encode-music.js   (needs ffmpeg)
const fs = require('fs');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');

const THEMES = ['ep0', 'ep1', 'ep2', 'ep3', 'ep4', 'ovh', 'boss', 'metal', 'defend', 'title'];
const MAX = 150, FADE = 3;
const root = path.join(__dirname, '..'), dir = path.join(root, 'music'), src = path.join(dir, 'src');

try { execFileSync('ffmpeg', ['-version'], { stdio: 'ignore' }); } catch (e) { console.error('ffmpeg is not installed'); process.exit(1); }
const byTheme = {};
for (const f of (fs.existsSync(src) ? fs.readdirSync(src) : []).sort()) {
  const m = f.match(new RegExp(`^(?:dn-)?(${THEMES.join('|')})[-_]?(\\d*|[ab])\\.(mp3|wav|m4a|flac|ogg)$`));
  if (m) (byTheme[m[1]] = byTheme[m[1]] || []).push(f);
  else console.log(`skipped ${f} (expected [dn-]<theme>[<n>].<ext>, theme in ${THEMES.join(' ')})`);
}
for (const f of fs.readdirSync(dir)) if (f.endsWith('.mp3')) fs.rmSync(path.join(dir, f));   // all derived
let size = 0;
for (const [theme, list] of Object.entries(byTheme)) {
  list.forEach((f, i) => {
    const inFile = path.join(src, f), out = path.join(dir, `${theme}-${i + 1}.mp3`);
    // ffmpeg prints the input's duration on stderr
    const info = spawnSync('ffmpeg', ['-i', inFile], { encoding: 'utf8' }).stderr.match(/Duration: (\d+):(\d+):([\d.]+)/);
    const dur = info ? +info[1] * 3600 + +info[2] * 60 + +info[3] : 0;
    const af = (dur > MAX ? `afade=t=out:st=${MAX - FADE}:d=${FADE},` : '') + 'loudnorm=I=-16:TP=-1.5:LRA=11';
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', inFile, '-t', String(MAX), '-af', af, '-ar', '44100', '-ac', '2', '-b:a', '96k', out]);
    size += fs.statSync(out).size;
    console.log(`${f} -> music/${path.basename(out)}  ${Math.min(dur, MAX).toFixed(0)} s, ${(fs.statSync(out).size / 1048576).toFixed(1)} MB`);
  });
}
const counts = THEMES.filter((t) => byTheme[t]).map((t) => `${t}: ${byTheme[t].length}`).join(', ');
fs.writeFileSync(path.join(root, 'js', 'music.js'),
  `'use strict';\n/* Soundtrack: versions of each theme in music/ (<theme>-1.mp3...). Generated by tools/encode-music.js, do not edit. */\nconst MUSIC = { ${counts} };\n`);
const missing = THEMES.filter((t) => !byTheme[t]);
console.log(`music/: ${Object.values(byTheme).flat().length} files, ${(size / 1048576).toFixed(1)} MB; js/music.js written`
  + (missing.length ? `; procedural music for ${missing.join(' ')}` : ''));
